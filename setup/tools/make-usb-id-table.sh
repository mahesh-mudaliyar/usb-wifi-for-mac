#!/bin/bash
# Regenerates setup/data/wifi-usb-ids.txt: every USB ID that a Wi-Fi driver in Alpine's linux-lts
# kernel claims, read straight from the drivers ("alias=usb:v....p...." in each module).
# Needs: xorriso and squashfs (brew install xorriso squashfs) and the Alpine CD in VMWIsoImages.
# Usage: bash setup/tools/make-usb-id-table.sh [alpine.iso]
set -e
HERE=$(cd "$(dirname "$0")/.." && pwd)
ISO=${1:-$HOME/Virtual Machines.localized/VMWIsoImages/alpine-standard-3.24.2-aarch64.iso}
W=$(mktemp -d "${TMPDIR:-/tmp}/usbids.XXXXXX"); trap 'rm -rf "$W"' EXIT
xorriso -osirrox on -indev "$ISO" -extract /boot/modloop-lts "$W/modloop" >/dev/null 2>&1
unsquashfs -q -d "$W/x" "$W/modloop" 'modules/*/kernel/drivers/net/wireless' >/dev/null
KVER=$(basename "$(find "$W/x/modules" -maxdepth 1 -name "*-lts" | head -1)")
OUT="$HERE/data/wifi-usb-ids.txt"
{
  echo "# USB Wi-Fi IDs supported by Alpine $(basename "$ISO" | sed 's/alpine-standard-//; s/-aarch64.iso//') (kernel $KVER)"
  echo "# Generated by setup/tools/make-usb-id-table.sh from the drivers' own ID tables."
  echo "# Format: vendor:product driver   (look up your dongle's ID; see docs/WIFI-ADAPTERS.md)"
  find "$W/x" -name '*.ko' | while read -r k; do
    m=$(basename "$k" .ko)
    strings -a "$k" | grep -E '^alias=usb:v[0-9A-F]{4}p[0-9A-F]{4}' |
      sed -E 's/^alias=usb:v([0-9A-F]{4})p([0-9A-F]{4}).*/\1:\2/' | tr 'A-F' 'a-f' | sort -u | sed "s/\$/ $m/"
  done | sort -u
} > "$OUT"
echo "Wrote $(grep -vc '^#' "$OUT") IDs to $OUT"
